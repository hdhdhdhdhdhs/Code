import explib as E
tot = 0; bad = 0

def t(job, args, want):
    global tot, bad
    tot += 1
    try:
        got = ' | '.join(job(args))
    except Exception as e:
        got = 'ERR ' + (str(e) or '?')
    ok = (got == want)
    if not ok: bad += 1
    print('  %s %-30s -> %-26s %s' % ('ok ' if ok else 'BAD', ' , '.join(args),
          got, '' if ok else '(want ' + want + ')'))

print('== zero and one ==')
t(E.do1, ['x^0'], '1')
t(E.do1, ['(5x)^0'], '1')
t(E.do1, ['(3^4)(3^-4)'], '1')
t(E.do1, ['2^5/2^5'], '1')
t(E.do1, ['x^7/x^3'], 'x^4')
t(E.do1, ['x^3/x^7'], '1/x^4')
print('== powers of products and quotients ==')
t(E.do1, ['(a^2b^3)^4'], 'a^8b^12')
t(E.do1, ['(a^2b^3)^-4'], '1/(a^8b^12)')
t(E.do1, ['(x/y)^3'], 'x^3/y^3')
t(E.do1, ['(x/y)^-3'], 'y^3/x^3')
t(E.do1, ['(2x^2)(3x^3)'], '6x^5')
t(E.do1, ['(2x^2)^3'], '2^3x^6 | = 8x^6')
